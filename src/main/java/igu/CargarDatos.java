    private void btnLimpiarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLimpiarActionPerformed

        // Al dar click en el boton limpiar, volvemos a "vacio" los campos de textos
        txtNombre.setText("");
        txtRaza.setText("");
        txtColor.setText("");
        txtNomDuenio.setText("");
        txtCelDuenio.setText("");
        txtObservaciones.setText("");

        // Con los combos no es lo mismo, al trabajar con indices, podemos setearle un indice nosotros, y ese seria el 0 ("-")
        cmbAlergico.setSelectedIndex(0);
        cmbAttEsp.setSelectedIndex(0);

    }//GEN-LAST:event_btnLimpiarActionPerformed

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        
        String nombreMasco = txtNombre.getText(); // Lo que la persona escriba en el campo de texto, el metodo getText, lo va a obtener y guardar en la variable
        String raza = txtRaza.getText();
        String color = txtColor.getText();
        String observaciones = txtObservaciones.getText();
        
        String alergico = (String) cmbAlergico.getSelectedItem(); // Con los combos, no funciona getText, ponemos getSelectedItem, para traer el item
        // Pero esto trae un objeto, lo que tenemos que hacer es un "casteo" delante de lo que queremos traer, entre paretesis, ponemos a lo que lo queremos convertir
        // en este caso, a un string para poder manipularlo mejor
        String atenEsp = (String) cmbAttEsp.getSelectedItem();
        
        String nombreDuenio = txtNomDuenio.getText();
        String celDuenio = txtCelDuenio.getText();
        
        control.guardar(nombreMasco, raza, color, observaciones, alergico, atenEsp, nombreDuenio, celDuenio);
        
        control.mostrarMensaje("Se guardo correctamente", "Info", "Guardado Exitoso");
        btnLimpiarActionPerformed(evt);
    }//GEN-LAST:event_btnGuardarActionPerformed

